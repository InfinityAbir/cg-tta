"""One command that rebuilds and checks everything in this release.

    python rebuild_all.py

It (1) runs the gate/metric self-test, (2) regenerates every table, CSV, JSON and
LaTeX fragment into a scratch directory from the stored predictions, (3) rebuilds
the revision tables (Center-1 locks, Phikon, held-out budget, Center-0 seed 5,
timing) from revision_colab/, and (4) compares each regenerated file with the
archived copy byte for byte.  The exit status is 0 only if all checks pass.
Figures are regenerated by code/make_figures.py (needs Times New Roman) and
code/make_cross_center_figure.py; their PNGs are compared when present.
Needs numpy, pandas and matplotlib on a CPU; no dataset images and no GPU.
"""
import filecmp
import os
import shutil
import subprocess
import sys
import tempfile

HERE = os.path.dirname(os.path.abspath(__file__))
PY = sys.executable
failures = []


def run(args, env_out=None, what=""):
    env = dict(os.environ)
    if env_out:
        env["CG_TTA_OUT"] = env_out
    r = subprocess.run([PY] + args, cwd=HERE, env=env, capture_output=True, text=True)
    ok = r.returncode == 0
    print(f"{'ok  ' if ok else 'FAIL'} {what or ' '.join(args)}")
    if not ok:
        failures.append(what or " ".join(args))
        print(r.stdout[-800:], r.stderr[-800:])
    return r


def compare(new_dir, ref_dir, names=None):
    n_same = 0
    for f in sorted(os.listdir(new_dir)):
        if names and f not in names:
            continue
        ref = os.path.join(ref_dir, f)
        if not os.path.isfile(ref):
            continue
        if filecmp.cmp(os.path.join(new_dir, f), ref, shallow=False):
            n_same += 1
        else:
            failures.append(f"differs from archive: {f}")
            print(f"FAIL differs: {f}")
    return n_same


if __name__ == "__main__":
    scratch = tempfile.mkdtemp(prefix="cgtta_rebuild_")
    core = os.path.join(scratch, "core")
    os.makedirs(core)
    run(["code/cg_tta.py", "--self-test"], what="self-test (gate, metrics, Table II, ablation, Center-0)")
    run(["code/reproduce_tables.py"], core, "core CSVs")
    run(["code/make_postsubmission_tables.py"], core, "Center-0 (5 seeds), full-EATA, Phikon probe CSVs")
    run(["code/harm_indicator_cross_center.py"], core, "cross-center harm indicator")
    run(["code/make_supplement_tables.py"], core, "14 supplement tables (generated, not typed)")
    run(["code/make_cost_table.py"], core, "class-conditional cost tables")
    run(["code/make_cross_center_figure.py"], core, "cross-center figure data")
    tabs = os.path.join(scratch, "tex")
    os.makedirs(tabs)
    for f in os.listdir(core):
        if f.endswith(".csv"):
            shutil.copy(os.path.join(core, f), tabs)
    run(["code/make_tables.py"], tabs, "LaTeX table fragments")
    same = compare(core, os.path.join(HERE, "tables"))
    same += compare(tabs, os.path.join(HERE, "tables"),
                    {f for f in os.listdir(tabs) if f.endswith(".tex")})
    fig = os.path.join(core, "fig_cross_center.png")
    if os.path.isfile(fig):
        if filecmp.cmp(fig, os.path.join(HERE, "figures", "fig_cross_center.png"), shallow=False):
            same += 1
        else:
            print("note: fig_cross_center.png differs byte-wise (matplotlib build); not a failure")
    rev = os.path.join(scratch, "revision")
    r = run(["colab_pro/postprocess_colab.py", "--root", "revision_colab",
             "--center2", "predictions/center2"], what="revision tables from revision_colab/")
    # postprocess writes into revision_colab/tables; compare with the shipped copy via git-free copy
    print(f"\n{same} regenerated files are byte-identical to the archived copies")
    shutil.rmtree(scratch, ignore_errors=True)
    if failures:
        print("REBUILD FAIL:", failures)
        sys.exit(1)
    print("REBUILD PASS")
