NBOOT = 5000


def load_npz(path, keys=("probabilities", "predictions", "labels")):
    z = np.load(path, allow_pickle=False)
    return {k: z[k] for k in keys}


def paths_center2(seed):
    d = os.path.join(FIX, f"seed{seed}")
    return {m: os.path.join(d, f"{m}.npz") for m in ("no", "tent", "flip", "eata", "shot")}


def paths_center0():
    # Single-seed pilot; the manuscript's Center-0 table uses seed 1..4 via
    # make_postsubmission_tables.py.
    d = os.path.join(REL, "predictions", "center0", "seed1")
    return {m: os.path.join(d, f"{m}.npz") for m in ("no", "tent", "flip", "eata", "shot")}


def acc(pred, lab):
    return float((pred == lab).mean())


def bal_acc(pred, lab):
    tpr = ((pred == 1) & (lab == 1)).sum() / max(1, (lab == 1).sum())
    tnr = ((pred == 0) & (lab == 0)).sum() / max(1, (lab == 0).sum())
    return float(0.5 * (tpr + tnr))


def ece15(prob, pred, lab):
    p = prob[:, 1].astype(float)
    conf = np.maximum(p, 1 - p)
    bins = np.linspace(0, 1, 16)
    idx = np.clip(np.digitize(conf, bins) - 1, 0, 14)
    e = 0.0
    for b in range(15):
        m = idx == b
        if m.any():
            e += m.mean() * abs(float((pred[m] == lab[m]).mean()) - float(conf[m].mean()))
    return float(e)


def boot_slide(d, seed):
    rng = np.random.default_rng(seed)
    d = np.asarray(d)
    vals = np.array([d[rng.integers(0, len(d), len(d))].mean() for _ in range(NBOOT)])
    return float(d.mean()), float(np.percentile(vals, 2.5)), float(np.percentile(vals, 97.5))


def p_wilcoxon(d):
    try:
        return float(wilcoxon(d, alternative="two-sided", zero_method="wilcox").pvalue)
    except ValueError:
        return float("nan")


def holm(pvals):
    order = np.argsort(pvals)
    m = len(pvals)
    adj = np.empty(m)
    running = 0.0
    for rank, i in enumerate(order):
        val = (m - rank) * pvals[i]
        running = max(running, val)
        adj[i] = min(1.0, running)
    return adj.tolist()


