"""Regenerate the core CSV tables from released predictions.

All numbers are derived from the saved paired predictions produced by
cg_tta_analysis.py, budget_common_support.py, and the original run outputs.
Writes the 13 core CSV tables into tables/ (set
CG_TTA_OUT to redirect). The four-seed Center-0, full-EATA and Phikon CSVs
are generated by make_postsubmission_tables.py; `core_table_center0.csv` here is
the single-seed pilot retained for provenance, not the manuscript table.
LaTeX fragments are generated separately by make_tables.py.
"""
