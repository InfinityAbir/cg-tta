methods = ["no", "tent", "flip", "eata", "shot", "safe_tent", "safe_eata", "safe_shot"]


def build(d, slides):
    out = {}
    p0 = d["no"]["probabilities"]
    y0 = d["no"]["predictions"].astype(int)
    lab = d["no"]["labels"].astype(int)
    pf = d["flip"]["probabilities"]
    yf = pf.argmax(1)
    out["no"] = (p0, y0)
    out["tent"] = (d["tent"]["probabilities"], d["tent"]["predictions"].astype(int))
    out["flip"] = (pf, yf)
    out["eata"] = (d["eata"]["probabilities"], d["eata"]["predictions"].astype(int))
    out["shot"] = (d["shot"]["probabilities"], d["shot"]["predictions"].astype(int))
    for name, key in [("safe_tent", "tent"), ("safe_eata", "eata"), ("safe_shot", "shot")]:
        p1 = d[key]["probabilities"]
        y1 = d[key]["predictions"].astype(int)
        accept = (y0 != y1) & (yf == y1)
        out[name] = (np.where(accept[:, None], p1, p0), np.where(accept, y1, y0))
    return out, lab, slides


def method_rows(pack, lab, slides, center, seed):
    rows, per_slide = [], []
    y0 = pack["no"][1]
    for name, (prob, pred) in pack.items():
        harm = int(((pred != lab) & (y0 == lab)).sum())
        help_ = int(((pred == lab) & (y0 != lab)).sum())
        try:
            auroc = float(roc_auc_score(lab, prob[:, 1]))
        except ValueError:
            auroc = float("nan")
        rows.append(dict(center=center, seed=seed, method=name, acc=acc(pred, lab),
                         ba=bal_acc(pred, lab), auroc=auroc, ece=ece15(prob, pred, lab),
                         help=help_, harm=harm, net=help_ - harm,
                         harm_rate=float(harm / max(1, (y0 == lab).sum()))))
        for s in np.unique(slides):
            m = slides == s
            if not m.any():
                continue
            hm = int(((pred[m] != lab[m]) & (y0[m] == lab[m])).sum())
            try:
                au = float(roc_auc_score(lab[m], prob[m, 1]))
            except ValueError:
                au = float("nan")
            per_slide.append(dict(center=center, seed=seed, slide=int(s), method=name,
                                  n=int(m.sum()), acc=acc(pred[m], lab[m]),
                                  ba=bal_acc(pred[m], lab[m]), auroc=au, ece=ece15(prob[m], pred[m], lab[m]),
                                  help=int(((pred[m] == lab[m]) & (y0[m] != lab[m])).sum()),
                                  harm=hm, net=int(((pred[m] == lab[m]) & (y0[m] != lab[m])).sum()) - hm,
                                  harm_rate=float(hm / max(1, (y0[m] == lab[m]).sum()))))
    return rows, per_slide


