# --------------------------------------------- gate ablation, matched random
gate_rows = []
for s in range(1, 6):
    pack, lab, sl = build(d2[s], slides2[s])
    y0 = pack["no"][1]
    yt = pack["tent"][1]
    yf = pack["flip"][1]
    ye = pack["eata"][1]
    flips = y0 != yt
    safe_accept = flips & (yf == yt)
    eata_accept = flips & (ye == yt)
    both_accept = safe_accept & eata_accept
    rng = np.random.default_rng(100 + s)
    k = int(safe_accept.sum())
    idx = rng.choice(np.where(flips)[0], size=k, replace=False)
    rand_accept = np.zeros_like(flips)
    rand_accept[idx] = True
    good = flips & (yt == lab)
    for name, m in [("all_flips", flips), ("random_matched", rand_accept),
                    ("flip_gate", safe_accept), ("eata_gate", eata_accept),
                    ("both_gate", both_accept), ("oracle", good)]:
        pred = np.where(m, yt, y0)
        harm = int(((pred != lab) & (y0 == lab)).sum())
        help_ = int(((pred == lab) & (y0 != lab)).sum())
        gate_rows.append(dict(seed=s, gate=name, accept=int(m.sum()),
                              accept_rate=float(m.sum() / max(1, flips.sum())),
                              acc=acc(pred, lab), help=help_, harm=harm, net=help_ - harm))
G = pd.DataFrame(gate_rows).groupby("gate").agg(
    accept=("accept", "mean"), accept_rate=("accept_rate", "mean"),
    acc=("acc", "mean"), help=("help", "mean"), harm=("harm", "mean"), net=("net", "mean"))
G = G.reindex(["all_flips", "random_matched", "flip_gate", "both_gate", "eata_gate", "oracle"])
